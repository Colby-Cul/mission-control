/**
 * monday-adapter.ts — Multi-tenant Monday.com data layer.
 *
 * Supports two tenants, each with its own API key env var:
 *   - `xome`        → process.env.MONDAY_XOME_API_KEY        (Xome Mortgage Team account)
 *   - `culbertson`  → process.env.MONDAY_CULBERTSON_API_KEY  (C&G account — legacy)
 *
 * Consumers call `getMondayData(widgetKey)` and receive:
 *   - on success:  `{ data: <transformed>, error: null }`
 *   - on missing key or any fetch error: `{ data: null, error: <message> }`
 *
 * Widgets treat `data: null` as the ComingSoon state and never crash server
 * components.
 *
 * All board/column/group/status mappings are pulled from the inventory
 * generated by `docs/xome-monday-inventory.json` during Phase 1 discovery.
 * Re-run `/tmp/xome-build-inventory.py` to regenerate.
 */

// ─── Types ──────────────────────────────────────────────────────────────

export type Tenant = 'xome' | 'culbertson'

export type WidgetKey =
  | 'xome.loan_pipeline'
  | 'xome.loan_officer_roster'
  | 'xome.loan_volume_kpis'
  | 'xome.compliance'
  | 'xome.warehouse_reconciliation'
  | 'xome.power'
  | 'xome.recent_closed_loans'
  | 'culbertson.loan_pipeline'            // legacy — not yet wired
  | 'culbertson.sales_volume_ytd'         // C&C Monday — Sales Volume YTD/MTD
  | 'culbertson.gci_ytd'                  // Gross commission income
  | 'culbertson.closed_transactions'      // Closed transaction count by period
  | 'culbertson.avg_commission_pct'       // Average commission %
  | 'culbertson.top_producers'            // Agent leaderboard by closed volume
  | 'culbertson.pipeline_value'           // Total $ in active deals
  | 'culbertson.revenue_by_source'        // Self-gen vs team-gen vs referral
  | 'culbertson.monthly_revenue'          // 12-month trend

export interface BoardMapping {
  tenant: Tenant
  widgetKey: WidgetKey
  boardId: string
  columns: Record<string, string>  // friendly -> monday column id
  groupMap?: Record<string, string>
  statusMap?: Record<string, string>
  transform?: (items: MondayItem[], mapping: BoardMapping) => unknown
}

export interface MondayItem {
  id: string
  name: string
  group?: { id: string; title: string }
  column_values: Array<{ id: string; type: string; text: string | null; value: string | null }>
}

export interface MondayResult<T = unknown> {
  data: T | null
  error: string | null
  cached?: boolean
}

// ─── Tenant → env var ────────────────────────────────────────────────────

const ENV_KEY_BY_TENANT: Record<Tenant, string> = {
  xome: 'MONDAY_XOME_API_KEY',
  culbertson: 'MONDAY_CULBERTSON_API_KEY',
}

function apiKeyForTenant(tenant: Tenant): string | null {
  const envVar = ENV_KEY_BY_TENANT[tenant]
  const v = process.env[envVar]
  return v && v.trim() ? v.trim() : null
}

// ─── In-memory cache (60s TTL) ──────────────────────────────────────────

interface CacheEntry {
  data: unknown
  expiresAt: number
}

const CACHE = new Map<string, CacheEntry>()
const CACHE_TTL_MS = 60_000

function cacheGet(key: string): unknown | null {
  const e = CACHE.get(key)
  if (!e) return null
  if (Date.now() > e.expiresAt) {
    CACHE.delete(key)
    return null
  }
  return e.data
}

function cacheSet(key: string, data: unknown): void {
  CACHE.set(key, { data, expiresAt: Date.now() + CACHE_TTL_MS })
}

// ─── GraphQL fetch ──────────────────────────────────────────────────────

export async function mondayFetch<T = unknown>(
  tenant: Tenant,
  query: string,
  variables: Record<string, unknown> = {}
): Promise<MondayResult<T>> {
  const apiKey = apiKeyForTenant(tenant)
  if (!apiKey) {
    return { data: null, error: `${ENV_KEY_BY_TENANT[tenant]} not configured` }
  }

  try {
    const res = await fetch('https://api.monday.com/v2', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: apiKey,
        'API-Version': '2024-01',
      },
      body: JSON.stringify({ query, variables }),
      cache: 'no-store',
    })

    if (res.status === 401) {
      return { data: null, error: '401 Unauthorized — bad or expired Monday token' }
    }
    if (res.status === 429) {
      return { data: null, error: '429 Rate limited by Monday API — try again in 60s' }
    }
    if (!res.ok) {
      return { data: null, error: `Monday API HTTP ${res.status}` }
    }

    const json = (await res.json()) as { data?: T; errors?: unknown[] }
    if (json.errors?.length) {
      return { data: null, error: `Monday API errors: ${JSON.stringify(json.errors)}` }
    }
    return { data: (json.data as T) ?? null, error: null }
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : String(err)
    return { data: null, error: msg }
  }
}


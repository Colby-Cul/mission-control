/**
 * monday-adapter.ts — Multi-tenant Monday.com data layer.
 *
 * Supports two tenants, each with its own API key env var:
 *   - `xome`        → process.env.MONDAY_XOME_API_KEY        (Xome Mortgage Team account)
 *   - `culbertson`  → process.env.MONDAY_CULBERTSON_API_KEY  (C&G account — legacy)
 *
 * Consumers call `getMondayData(widgetKey)` and receive:
 *   - on success:  `{ data: <transformed>, error: null }`
 *   - on missing key or any fetch error: `{ data: null, error: <message> }`
 *
 * Widgets treat `data: null` as the ComingSoon state and never crash server
 * components.
 *
 * All board/column/group/status mappings are pulled from the inventory
 * generated by `docs/xome-monday-inventory.json` during Phase 1 discovery.
 * Re-run `/tmp/xome-build-inventory.py` to regenerate.
 */


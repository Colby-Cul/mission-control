function transformRecentClosed(items: MondayItem[], m: BoardMapping, limit = 10): ClosedLoanRow[] {
  const rows: ClosedLoanRow[] = []
  for (const it of items) {
    const stage = cvText(it, m.columns.stage) || ''
    const groupId = it.group?.id ?? ''
    const isFunded = stage === 'Funded' || groupId === 'new_group62657'
    if (!isFunded) continue

    const amount =
      parseNum(cvText(it, m.columns.le_loan_amount)) ||
      parseNum(cvText(it, m.columns.est_loan_amount))
    const closeStr = cvText(it, m.columns.coe) || cvText(it, m.columns.wire_disbursement) || null

    rows.push({
      id: it.id,
      borrower: redactName(it.name, cvText(it, m.columns.first_name)),
      amount,
      lo: cvText(it, m.columns.lo) || '—',
      state: cvText(it, m.columns.property_state) || '—',
      loan_type: cvText(it, m.columns.loan_type) || '—',
      loan_purpose: cvText(it, m.columns.loan_purpose) || '—',
      close_date: closeStr,
    })
  }
  rows.sort((a, b) => {
    const ad = a.close_date ? new Date(a.close_date).getTime() : 0
    const bd = b.close_date ? new Date(b.close_date).getTime() : 0
    return bd - ad
  })
  return rows.slice(0, limit)
}

interface ComplianceView {
  board_id: string
  total_items: number
  pending_count: number
  completed_count: number
  overdue_count: number
  items: Array<{
    id: string
    name: string
    group: string
    date_received: string | null
    processor_compliance: string
    invoice_status: string
    cleared: string
    overdue: boolean
  }>
}

function transformCompliance(items: MondayItem[], m: BoardMapping): ComplianceView {
  const now = Date.now()
  const overdueWindowMs = 14 * 86_400_000

  const rows = items.map(it => {
    const dateStr = cvText(it, m.columns.date_received)
    const date = dateStr ? new Date(dateStr) : null
    const overdue =
      !!date && !isNaN(date.getTime()) && now - date.getTime() > overdueWindowMs &&
      !cvText(it, m.columns.cleared).toLowerCase().includes('yes')
    const gid = it.group?.id ?? ''
    const gname = m.groupMap?.[gid] ?? it.group?.title ?? 'Other'
    return {
      id: it.id,
      name: it.name,
      group: gname,
      date_received: dateStr || null,
      processor_compliance: cvText(it, m.columns.processor_compliance),
      invoice_status: cvText(it, m.columns.invoice_status),
      cleared: cvText(it, m.columns.cleared),
      overdue,
    }
  })

  const pending_count = rows.filter(r => r.group === 'Pending Compliance').length
  const completed_count = rows.filter(r => r.group === 'Compliance Completed').length
  const overdue_count = rows.filter(r => r.overdue).length

  return {
    board_id: m.boardId,
    total_items: items.length,
    pending_count,
    completed_count,
    overdue_count,
    items: rows.slice(0, 20),
  }
}

interface WarehouseView {
  board_id: string
  open_count: number
  reconciled_count: number
  total_pending_value: number
  total_haircut: number
  oldest_open_days: number | null
}

function transformWarehouse(items: MondayItem[], m: BoardMapping): WarehouseView {
  let open_count = 0
  let reconciled_count = 0
  let total_pending_value = 0
  let total_haircut = 0
  let oldest_ms: number | null = null
  const now = Date.now()

  for (const it of items) {
    const gid = it.group?.id ?? ''
    const amount = parseNum(cvText(it, m.columns.total_wire)) || parseNum(cvText(it, m.columns.loan_amount_mirror))
    const haircut = parseNum(cvText(it, m.columns.haircut))

    if (gid === 'topics') {
      open_count++
      total_pending_value += amount
      total_haircut += haircut
      const fundedStr = cvText(it, m.columns.funded_date_mirror)
      if (fundedStr) {
        const d = new Date(fundedStr).getTime()
        if (!isNaN(d) && (oldest_ms === null || d < oldest_ms)) oldest_ms = d
      }
    } else if (gid === 'group_title') {
      reconciled_count++
    }
  }

  const oldest_open_days =
    oldest_ms !== null ? Math.floor((now - oldest_ms) / 86_400_000) : null

  return {
    board_id: m.boardId,
    open_count,
    reconciled_count,
    total_pending_value,
    total_haircut,
    oldest_open_days,
  }
}

interface XomePowerView {
  board_id: string
  total_items: number
  stages: Array<{ group_id: string; group_name: string; count: number }>
  items: Array<{ id: string; name: string; group: string; stage: string; contacted: string; city: string }>
}

function transformXomePower(items: MondayItem[], m: BoardMapping): XomePowerView {
  const groupMap = m.groupMap ?? {}
  const stages: Record<string, { group_id: string; group_name: string; count: number }> = {}
  for (const [gid, gname] of Object.entries(groupMap)) {
    stages[gid] = { group_id: gid, group_name: gname, count: 0 }
  }
  for (const it of items) {
    const gid = it.group?.id ?? 'unknown'
    if (!stages[gid]) {
      stages[gid] = { group_id: gid, group_name: it.group?.title ?? 'Other', count: 0 }
    }
    stages[gid].count++
  }
  return {
    board_id: m.boardId,
    total_items: items.length,
    stages: Object.values(stages),
    items: items.slice(0, 10).map(it => {
      const lastName = (it.name || '').split(' ')[0] || '—'
      return {
        id: it.id,
        name: `${lastName[0]?.toUpperCase() || ''}. ${it.name?.split(' ').slice(1).join(' ') || ''}`.trim() || it.name,
        group: m.groupMap?.[it.group?.id ?? ''] ?? it.group?.title ?? 'Other',
        stage: cvText(it, m.columns.stage),
        contacted: cvText(it, m.columns.contacted),
        city: cvText(it, m.columns.city),
      }
    }),
  }
}

// ─── Public API ─────────────────────────────────────────────────────────

export async function getMondayData(widgetKey: WidgetKey): Promise<MondayResult> {
  const mapping = MAPPING_BY_KEY[widgetKey]
  if (!mapping) {
    return { data: null, error: `Unknown widget key: ${widgetKey}` }
  }

  const cacheKey = `${mapping.tenant}:${widgetKey}`
  const cached = cacheGet(cacheKey)
  if (cached) {
    return { data: cached, error: null, cached: true }
  }

  // If no API key, short-circuit with explicit error
  if (!apiKeyForTenant(mapping.tenant)) {
    return { data: null, error: `${ENV_KEY_BY_TENANT[mapping.tenant]} not configured` }
  }

  // Collect column IDs we need + always include `name`, `group`
  const columnIds = Array.from(new Set(Object.values(mapping.columns))).filter(Boolean)
  const result = await fetchBoardItems(mapping.tenant, mapping.boardId, columnIds)
  if (result.error || !result.data) {
    return { data: null, error: result.error ?? 'No items returned' }
  }

  let transformed: unknown
  try {
    switch (widgetKey) {
      case 'xome.loan_pipeline':
        transformed = transformLoanPipeline(result.data, mapping)
        break
      case 'xome.loan_officer_roster':
        transformed = transformLoanOfficers(result.data, mapping)
        break
      case 'xome.loan_volume_kpis':
        transformed = transformLoanVolumeKPIs(result.data, mapping)
        break
      case 'xome.recent_closed_loans':
        transformed = transformRecentClosed(result.data, mapping)
        break
      case 'xome.compliance':
        transformed = transformCompliance(result.data, mapping)
        break
      case 'xome.warehouse_reconciliation':
        transformed = transformWarehouse(result.data, mapping)
        break
      case 'xome.power':
        transformed = transformXomePower(result.data, mapping)
        break
      default:
        transformed = result.data
    }
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : String(err)
    return { data: null, error: `Transform failed: ${msg}` }
  }

  cacheSet(cacheKey, transformed)
  return { data: transformed, error: null }
}


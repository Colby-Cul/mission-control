// ─── Redaction helpers (for borrower display) ──────────────────────────

export function redactName(lastName: string | null, firstName?: string | null): string {
  const last = (lastName || '').trim()
  const first = (firstName || '').trim()
  if (first && last) return `${first[0]?.toUpperCase() ?? ''}. ${last}`
  if (last) return last
  if (first) return `${first[0]?.toUpperCase() ?? ''}.`
  return '—'
}

function parseNum(text: string | null | undefined): number {
  if (!text) return 0
  const n = Number(String(text).replace(/[^0-9.-]/g, ''))
  return Number.isFinite(n) ? n : 0
}

function cvText(item: MondayItem, id: string | undefined): string {
  if (!id) return ''
  const cv = item.column_values.find(c => c.id === id)
  return cv?.text ?? ''
}

// ─── Board fetchers ─────────────────────────────────────────────────────

/**
 * Paginate through all items on a board using cursor-based items_page.
 * Returns a flat array of items with the specified column_values.
 */
async function fetchBoardItems(
  tenant: Tenant,
  boardId: string,
  columnIds: string[],
  pageSize = 200
): Promise<MondayResult<MondayItem[]>> {
  const firstQuery = `
    query ($boardId: ID!, $columnIds: [String!], $limit: Int!) {
      boards(ids: [$boardId]) {
        items_page(limit: $limit) {
          cursor
          items {
            id
            name
            group { id title }
            column_values(ids: $columnIds) { id type text value }
          }
        }
      }
    }
  `
  const nextQuery = `
    query ($cursor: String!, $columnIds: [String!], $limit: Int!) {
      next_items_page(cursor: $cursor, limit: $limit) {
        cursor
        items {
          id
          name
          group { id title }
          column_values(ids: $columnIds) { id type text value }
        }
      }
    }
  `

  const r = await mondayFetch<{
    boards: Array<{ items_page: { cursor: string | null; items: MondayItem[] } }>
  }>(tenant, firstQuery, { boardId, columnIds, limit: pageSize })

  if (r.error || !r.data) return { data: null, error: r.error ?? 'No data' }

  const collected: MondayItem[] = []
  let cursor = r.data.boards?.[0]?.items_page?.cursor ?? null
  collected.push(...(r.data.boards?.[0]?.items_page?.items ?? []))

  // Safety cap to avoid infinite loops (board has 928 items; cap at ~5k)
  let hops = 0
  while (cursor && hops < 25) {
    hops++
    const n = await mondayFetch<{
      next_items_page: { cursor: string | null; items: MondayItem[] }
    }>(tenant, nextQuery, { cursor, columnIds, limit: pageSize })
    if (n.error || !n.data) break
    collected.push(...(n.data.next_items_page?.items ?? []))
    cursor = n.data.next_items_page?.cursor ?? null
  }

  return { data: collected, error: null }
}

// ─── Widget transforms ──────────────────────────────────────────────────

interface LoanPipelineStage {
  group_id: string
  group_name: string
  count: number
  total_amount: number
}

interface LoanPipelineView {
  board_id: string
  total_items: number
  total_active_amount: number
  stages: LoanPipelineStage[]
  generated_at: string
}

function transformLoanPipeline(items: MondayItem[], m: BoardMapping): LoanPipelineView {
  const groupMap = m.groupMap ?? {}
  const stages: Record<string, LoanPipelineStage> = {}

  // Seed every group so empty stages still render
  for (const [gid, gname] of Object.entries(groupMap)) {
    stages[gid] = { group_id: gid, group_name: gname, count: 0, total_amount: 0 }
  }

  for (const it of items) {
    const gid = it.group?.id ?? 'unknown'
    const gname = groupMap[gid] ?? it.group?.title ?? 'Other'
    if (!stages[gid]) stages[gid] = { group_id: gid, group_name: gname, count: 0, total_amount: 0 }
    stages[gid].count++

    // Prefer LE loan amount → estimated loan amount → estimated value
    const amount =
      parseNum(cvText(it, m.columns.le_loan_amount)) ||
      parseNum(cvText(it, m.columns.est_loan_amount)) ||
      parseNum(cvText(it, m.columns.estimated_value))
    stages[gid].total_amount += amount
  }

  // Keep the groups in the same declaration order as groupMap; unknowns last
  const ordered: LoanPipelineStage[] = []
  const seen = new Set<string>()
  for (const gid of Object.keys(groupMap)) {
    if (stages[gid]) {
      ordered.push(stages[gid])
      seen.add(gid)
    }
  }
  for (const [gid, s] of Object.entries(stages)) {
    if (!seen.has(gid)) ordered.push(s)
  }

  const active_groups = new Set(['topics', 'new_group23653', 'new_group41491', 'group_mks3286t'])
  const total_active_amount = ordered
    .filter(s => active_groups.has(s.group_id))
    .reduce((sum, s) => sum + s.total_amount, 0)

  return {
    board_id: m.boardId,
    total_items: items.length,
    total_active_amount,
    stages: ordered,
    generated_at: new Date().toISOString(),
  }
}

interface LoanOfficerRow {
  name: string
  loan_count: number
  active_count: number
  funded_count: number
  volume_mtd: number
  volume_ytd: number
}

function transformLoanOfficers(items: MondayItem[], m: BoardMapping): LoanOfficerRow[] {
  const now = new Date()
  const mtdStart = new Date(now.getFullYear(), now.getMonth(), 1)
  const ytdStart = new Date(now.getFullYear(), 0, 1)

  const officers = new Map<string, LoanOfficerRow>()

  for (const it of items) {
    const loText = cvText(it, m.columns.lo)
    const loName = loText?.trim() || 'Unassigned'
    if (!officers.has(loName)) {
      officers.set(loName, {
        name: loName,
        loan_count: 0,
        active_count: 0,
        funded_count: 0,
        volume_mtd: 0,
        volume_ytd: 0,
      })
    }
    const rec = officers.get(loName)!
    rec.loan_count++

    const stage = cvText(it, m.columns.stage) || ''
    const groupId = it.group?.id ?? ''
    const isFunded = stage === 'Funded' || groupId === 'new_group62657'
    const isDead = groupId === 'new_group9764' || groupId === 'new_group13782'

    if (isFunded) rec.funded_count++
    else if (!isDead) rec.active_count++

    const amount =
      parseNum(cvText(it, m.columns.le_loan_amount)) ||
      parseNum(cvText(it, m.columns.est_loan_amount))
    const closeStr = cvText(it, m.columns.coe) || cvText(it, m.columns.wire_disbursement)

    if (isFunded && amount > 0 && closeStr) {
      const closeDate = new Date(closeStr)
      if (!isNaN(closeDate.getTime())) {
        if (closeDate >= ytdStart) rec.volume_ytd += amount
        if (closeDate >= mtdStart) rec.volume_mtd += amount
      }
    }
  }

  return Array.from(officers.values())
    .filter(r => r.name !== 'Unassigned')
    .sort((a, b) => b.volume_ytd - a.volume_ytd || b.funded_count - a.funded_count)
}

interface LoanVolumeKPIs {
  volume_mtd: number
  volume_ytd: number
  loans_funded_mtd: number
  loans_funded_ytd: number
  avg_loan_size: number
  pipeline_value: number
  pipeline_count: number
  avg_days_to_close: number | null
  pull_through_rate: number | null
}

function transformLoanVolumeKPIs(items: MondayItem[], m: BoardMapping): LoanVolumeKPIs {
  const now = new Date()
  const mtdStart = new Date(now.getFullYear(), now.getMonth(), 1)
  const ytdStart = new Date(now.getFullYear(), 0, 1)

  let volume_mtd = 0
  let volume_ytd = 0
  let loans_funded_mtd = 0
  let loans_funded_ytd = 0
  let funded_sum = 0
  let funded_count = 0
  let pipeline_value = 0
  let pipeline_count = 0
  const closeDays: number[] = []

  const active_groups = new Set(['topics', 'new_group23653', 'new_group41491', 'group_mks3286t'])

  for (const it of items) {
    const stage = cvText(it, m.columns.stage) || ''
    const groupId = it.group?.id ?? ''
    const isFunded = stage === 'Funded' || groupId === 'new_group62657'

    const amount =
      parseNum(cvText(it, m.columns.le_loan_amount)) ||
      parseNum(cvText(it, m.columns.est_loan_amount))

    if (isFunded && amount > 0) {
      const closeStr = cvText(it, m.columns.coe) || cvText(it, m.columns.wire_disbursement)
      const closeDate = closeStr ? new Date(closeStr) : null
      const createdStr = cvText(it, m.columns.created_at)
      const createdDate = createdStr ? new Date(createdStr) : null

      funded_sum += amount
      funded_count++

      if (closeDate && !isNaN(closeDate.getTime())) {
        if (closeDate >= ytdStart) {
          volume_ytd += amount
          loans_funded_ytd++
        }
        if (closeDate >= mtdStart) {
          volume_mtd += amount
          loans_funded_mtd++
        }
        if (createdDate && !isNaN(createdDate.getTime())) {
          const days = Math.round((closeDate.getTime() - createdDate.getTime()) / 86_400_000)
          if (days > 0 && days < 365) closeDays.push(days)
        }
      }
    }

    if (active_groups.has(groupId)) {
      pipeline_count++
      pipeline_value += amount
    }
  }

  const avg_days_to_close =
    closeDays.length > 0 ? Math.round(closeDays.reduce((a, b) => a + b, 0) / closeDays.length) : null
  const avg_loan_size = funded_count > 0 ? funded_sum / funded_count : 0
  const totalCountable = items.filter(it => {
    const gid = it.group?.id ?? ''
    return gid !== 'new_group9764' && gid !== 'new_group13782'
  }).length
  const pull_through_rate = totalCountable > 0 ? funded_count / totalCountable : null

  return {
    volume_mtd,
    volume_ytd,
    loans_funded_mtd,
    loans_funded_ytd,
    avg_loan_size,
    pipeline_value,
    pipeline_count,
    avg_days_to_close,
    pull_through_rate,
  }
}

